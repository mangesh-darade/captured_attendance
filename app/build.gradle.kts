fun obfuscateToHex(input: String, salt: Int): String {
  val bytes = input.toByteArray(Charsets.UTF_8)
  return bytes.joinToString("") { b ->
    val xorVal = (b.toInt() xor salt) and 0xFF
    String.format("%02x", xorVal)
  }
}

